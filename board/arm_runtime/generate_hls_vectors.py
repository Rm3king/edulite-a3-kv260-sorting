#!/usr/bin/python3
"""Generate deterministic planner/HLS integration cases, never robot commands."""
import argparse
import json
import random
from pathlib import Path
from joint_trajectory import JointPlanner


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--positions', type=Path)
    ap.add_argument('--header', type=Path, required=True)
    ap.add_argument('--report', type=Path, required=True)
    args = ap.parse_args()
    p = JointPlanner(); cases = []
    if args.positions:
        capture = json.loads(args.positions.read_text())
        if capture['status'] != 'PASS_READ_ONLY_ALL_7':
            raise ValueError('complete read-only sample required')
        q = [x['position_joint_rad'] for x in sorted(capture['joint_reference_latest'], key=lambda x:x['motor'])]
        q += [capture['gripper_reference']['position_motor_rad']]
        cases.append(p.movej(q, [0.]*7))
        goal = [x+d for x,d in zip(q, [.02,.005,-.005,-.02,.01,-.01,.02])]
        cases.append(p.movej(q, goal))
    rng = random.Random(2617)
    for _ in range(32):
        q = [rng.uniform(l+.05,h-.05) for l,h in zip(p.lower,p.upper)]
        goal = [min(h-.01,max(l+.01,x+rng.uniform(-.03,.03))) for x,l,h in zip(q,p.lower,p.upper)]
        cases.append(p.movej(q,goal))
        cases.append(p.brake(q, [rng.uniform(-v*.5,v*.5) for v in p.velocity]))
    # Exact endpoint cases at configured joint limits exercise quantization.
    # Boundary-local moves stay within the configured 600 s segment budget;
    # full shoulder/elbow travel is deliberately not a commissioning case.
    cases += [p.movej(p.lower,[x+.01 for x in p.lower]),
              p.movej(p.upper,[x-.01 for x in p.upper])]
    def array(v):
        if isinstance(v,list):return '{'+','.join(array(x) for x in v)+'}'
        return format(v,'.17g')
    bounds = [sorted((l*d+o,h*d+o)) for l,h,d,o in zip(p.lower,p.upper,p.direction,p.offset)]
    header = ('// Generated by contest/arm_runtime/generate_hls_vectors.py; no motor execution.\n'
              f'const int arm_case_count={len(cases)};\n'
              'const double arm_coefficients[][7][4]='+array([x['motor_coefficients_rad'] for x in cases])+';\n'
              'const double arm_lower[7]='+array([x[0] for x in bounds])+';\n'
              'const double arm_upper[7]='+array([x[1] for x in bounds])+';\n')
    args.header.write_text(header)
    args.report.write_text(json.dumps({'status':'GENERATED_NOT_EXECUTED','cases':cases,'motion_commands_sent':0},indent=2)+'\n')
    print(f'Generated {len(cases)} planner/HLS cases')


if __name__ == '__main__':main()
